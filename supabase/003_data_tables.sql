-- Step 3 of 7: data tables, constraints and indexes.

create table if not exists public.products (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null references auth.users(id),
  lab             text,
  qr_code         text,
  name            text not null,
  description     text,
  quantity        integer not null,
  expiry_date     date not null,
  created_at      timestamp default now(),
  org_id          uuid references public.organizations(id) on delete set null,
  low_stock_level integer not null default 0,
  unit            text not null default 'units'
);

create table if not exists public.usage_logs (
  id         bigint generated by default as identity primary key,
  product_id uuid not null references public.products(id) on delete cascade,
  user_id    uuid not null default auth.uid(),
  amount     integer not null check (amount > 0),
  note       text,
  created_at timestamptz not null default now()
);
create index if not exists usage_logs_product_time on public.usage_logs (product_id, created_at desc);

create table if not exists public.equipment (
  id         uuid primary key default gen_random_uuid(),
  org_id     uuid default public.lt_org(),
  owner_id   uuid not null default auth.uid(),
  name       text not null,
  lab        text not null,
  asset_code text,
  created_at timestamptz not null default now(),
  service_due date
);

create table if not exists public.equipment_bookings (
  id           uuid primary key default gen_random_uuid(),
  equipment_id uuid not null references public.equipment(id) on delete cascade,
  user_id      uuid not null default auth.uid(),
  kind         text not null default 'booking' check (kind in ('booking','maintenance')),
  purpose      text,
  starts_at    timestamptz not null,
  ends_at      timestamptz not null,
  status       text not null default 'active' check (status in ('active','returned','cancelled')),
  returned_at  timestamptz,
  created_at   timestamptz not null default now(),
  check (ends_at > starts_at),
  -- the key rule: no two ACTIVE bookings of the same equipment may overlap in time
  constraint no_overlap exclude using gist
    (equipment_id with =, tstzrange(starts_at, ends_at) with &&)
    where (status = 'active')
);
create index if not exists eb_equipment_time on public.equipment_bookings (equipment_id, starts_at);

create table if not exists public.booking_attempts (
  id           bigint generated by default as identity primary key,
  org_id       uuid,
  user_id      uuid not null default auth.uid(),
  equipment_id uuid not null references public.equipment(id) on delete cascade,
  starts_at    timestamptz not null,
  ends_at      timestamptz not null,
  outcome      text not null check (outcome in ('booked','conflict','maintenance')),
  created_at   timestamptz not null default now()
);

create table if not exists public.feedback (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references auth.users(id) on delete cascade,
  email      text,
  rating     integer check (rating >= 1 and rating <= 5),
  category   text not null default 'suggestion'
             check (category in ('suggestion','problem','compliment','other')),
  message    text not null check (char_length(message) between 3 and 1000),
  page       text,
  created_at timestamptz default now()
);

create table if not exists public.teacher_requests (
  id            uuid primary key default gen_random_uuid(),
  user_id       uuid not null references auth.users(id) on delete cascade,
  org_id        uuid references public.organizations(id) on delete cascade,
  designation   text not null,
  proof_path    text,
  status        text not null default 'pending'
                check (status in ('pending','approved','rejected','flagged','needs_review','reported')),
  admin_note    text,
  created_at    timestamptz default now(),
  reviewed_at   timestamptz,
  ai_result     jsonb,
  ai_checked_at timestamptz,
  reported_to   text,
  reported_at   timestamptz
);

create table if not exists public.teacher_verifications (
  id             uuid primary key default gen_random_uuid(),
  user_id        uuid not null references auth.users(id) on delete cascade,
  email          text,
  full_name      text not null,
  org_name       text not null,
  employee_id    text,
  id_image_path  text,
  id_hash        text,
  id_last4       text,
  status         text not null default 'pending'
                 check (status in ('pending','approved','flagged','rejected','reported','revoked')),
  suspicion      text not null default 'none' check (suspicion in ('none','low','high')),
  auto_decided   boolean not null default false,
  ai_result      jsonb,
  reasons        text[] not null default '{}',
  admin_note     text,
  decided_at     timestamptz,
  reported_to    text,
  reported_at    timestamptz,
  created_at     timestamptz not null default now()
);
create index if not exists tv_user_idx   on public.teacher_verifications (user_id, created_at desc);
create index if not exists tv_hash_idx   on public.teacher_verifications (id_hash);
create index if not exists tv_status_idx on public.teacher_verifications (status);

-- small keep-alive table
create table if not exists public.ping (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now()
);
